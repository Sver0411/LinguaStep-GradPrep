/**
 * Fill each study band from the bundled, curated expansion when a scanned
 * book term was not legible enough for exact OCR matching. These are still
 * common exam-oriented entries, and are tagged separately in the UI.
 */
const QUOTA_FILL_TERMS = (() => {
  const selected = new Set(verified);
  const levelOverrides = new Map<string, string>();
  const levels = ["N1", "N2", "N3"] as const;
  for (const level of levels) {
    const current = new Set(
      EXPANDED_WORDS
        .filter((word) => selected.has(word.japanese.term) && word.japanese.difficulty.includes(level))
        .map((word) => word.japanese.term),
    );
    const needed = Math.max(0, 800 - current.size);
    if (!needed) continue;
    const candidates = EXPANDED_WORDS.filter(
      (word) =>
        !selected.has(word.japanese.term) &&
        word.japanese.difficulty.includes(level) &&
        word.japanese.term.length >= 2 &&
        /[ぁ-んァ-ヶ一-龯]/.test(word.japanese.term) &&
        /^[A-Za-z][A-Za-z -]*$/.test(word.english.term) &&
        !["ちんちん", "一人物"].includes(word.japanese.term),
    ).sort((left, right) => {
      const rank = { 高频: 0, 常用: 1, 普通: 2, 低频: 3 } as const;
      return (rank[left.frequency as keyof typeof rank] ?? 9) - (rank[right.frequency as keyof typeof rank] ?? 9);
    });
    const uniqueCandidates = candidates.filter((word, index, all) =>
      all.findIndex((candidate) => candidate.japanese.term === word.japanese.term) === index,
    );
    for (const word of uniqueCandidates.slice(0, needed)) {
      selected.add(word.japanese.term);
      levelOverrides.set(word.japanese.term, `JLPT ${level}`);
    }
  }
  return {
    terms: [...selected].filter((term) => !verified.has(term)),
    levelOverrides,
  };
})();
for (const term of QUOTA_FILL_TERMS.terms) verified.add(term);
const quotaFillTerms = new Set<string>(QUOTA_FILL_TERMS.terms);
for (const [term, level] of QUOTA_FILL_TERMS.levelOverrides) sourceLevelOverrides.set(term, level);

// Resolve duplicate headwords deterministically so the three visible study
// bands each contain 800 unique entries rather than counting one term twice.
const assignedStudyTerms = new Set<string>();
for (const level of ["N1", "N2", "N3"] as const) {
  const candidates = EXPANDED_WORDS
    .filter((word) => verified.has(word.japanese.term) && word.japanese.difficulty.includes(level))
    .filter((word, index, all) => all.findIndex((item) => item.japanese.term === word.japanese.term) === index)
    .filter((word) => !assignedStudyTerms.has(word.japanese.term));
  for (const word of candidates.slice(0, 800)) {
    assignedStudyTerms.add(word.japanese.term);
    sourceLevelOverrides.set(word.japanese.term, `JLPT ${level}`);
  }
}

